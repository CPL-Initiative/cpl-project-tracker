    var fLead = el("input", { "type": "text", "class": "padd-in", "placeholder": "Lead (person)" });
    var fStatus = el("select", { "class": "padd-in" });
    ["Not Started", "In Progress", "On Track", "Completed"].forEach(function (s) {
      fStatus.appendChild(el("option", { "value": s }, [s]));
    });
    var fStart = el("input", { "type": "date", "class": "padd-in" });
    var fEnd = el("input", { "type": "date", "class": "padd-in" });

    modal.appendChild(field("ID", fId));
    modal.appendChild(field("Name", fName));
    modal.appendChild(field("Description", fDesc));
    modal.appendChild(field("Activity", fAct));
    modal.appendChild(field("CPL Goal", fGoal));
    modal.appendChild(field("Lead", fLead));
    modal.appendChild(field("Status", fStatus));
    var dates = el("div", { "class": "padd-dates" }, [field("Start", fStart), field("End", fEnd)]);
    modal.appendChild(dates);
    modal.appendChild(statusEl);

    var actions = el("div", { "class": "padd-actions" }, []);
    var cancel = el("button", { "class": "padd-cancel", "type": "button" }, ["Cancel"]);
    var save = el("button", { "class": "padd-save", "type": "button" }, ["Add project"]);
    cancel.addEventListener("click", closeModal);
    actions.appendChild(cancel);
    actions.appendChild(save);
    modal.appendChild(actions);

    // Suggest the next free 5.N from the LIVE id list (includes tabled rows).
