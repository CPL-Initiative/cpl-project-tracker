  function genSlug(kind) {
    var pre = KIND_SLUG_PREFIX[kind] || "x";
    var re = new RegExp("^" + pre + "(\\d+)$");
    var max = 0;
    Object.keys(byId).forEach(function (s) { var m = re.exec(s); if (m) { var n = parseInt(m[1], 10); if (n > max) max = n; } });
    return pre + (max + 1);
  }
