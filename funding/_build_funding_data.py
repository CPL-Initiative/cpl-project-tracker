#!/usr/bin/env python3
"""Extract the CPL Implementation Funding model workbook into cpl_funding_data.js.

One-shot, re-runnable extractor (same spirit as kb/_seed_college_short_names.py):
reads funding/CPL_Funding_Model_2026.xlsx (sheet "CPL IMPLEMENTATION MODEL 2026")
and emits ../cpl_funding_data.js carrying `window.CPL_FUNDING` for the
Implementation Funding tab (cpl_funding.js). The output is a STATIC committed
asset — it is NOT regenerated by the daily cron. When Sam ships a new model
workbook, drop it at funding/CPL_Funding_Model_2026.xlsx (or pass a path) and
re-run:

    python3 funding/_build_funding_data.py [path/to/model.xlsx]

Workbook shape (2026-06-11 edition):
  row 2-3   funding-pool block: pool headers + values (one-time funds, admin,
            scaling, per-year available college funding, headcount, $/student)
  row 5-6   college-table headers + FUNDING FACTOR / PROJECTED HEADCOUNT subheads
  row 7     the model constants: per-priority funding factor + projection rate
  row 8     ORDER 0 "SYSTEM" — the statewide totals row
  rows 9+   one row per college; trailing rows = average-allocation + footnotes

Model math (verified against every row at extract time):
  per_student = available_per_year / ccc_headcount
  allocation[p] = headcount * rate[p] * factor[p] * per_student
  Σ(rate*factor) over the 3 priorities = 1.0, so a college's total potential
  allocation is exactly its headcount share of one $11.6M annual tranche.

PII: institutional + U.S. Census aggregates only (college/district/county names,
headcounts, dollars). No person-level data anywhere in the workbook.
"""
import json
import os
import sys

from openpyxl import load_workbook

HERE = os.path.dirname(os.path.abspath(__file__))
DEFAULT_XLSX = os.path.join(HERE, "CPL_Funding_Model_2026.xlsx")
OUT_JS = os.path.join(HERE, "..", "cpl_funding_data.js")
SHEET = "CPL IMPLEMENTATION MODEL 2026"

# The three funding priorities. Descriptions + metrics live in the row-5 header
# cells; keep these labels in sync with the workbook if a future edition
# reorders them.
PRIORITY_KEYS = ("p1", "p2", "p3")


def _num(v):
    """Round floats for a stable, diff-friendly artifact (cents / 6-sig pcts)."""
    if v is None or v == "":
        return None
    if isinstance(v, str):
        return v.strip()
    f = float(v)
    if f == int(f) and abs(f) < 1e15:
        return int(f)
    return round(f, 6)


def _money(v):
    f = float(v)
    return round(f, 2)


def _parse_priority_header(cell):
    """Row-5 priority cells: 'PRIORITY n\\n<description>\\n…\\nMETRIC: <metric>'."""
    lines = [ln.strip() for ln in str(cell).splitlines() if ln.strip()]
    label = lines[0].title() if lines else ""
    desc, metric = "", ""
    for ln in lines[1:]:
        if ln.upper().startswith("METRIC"):
            metric = ln.split(":", 1)[1].strip() if ":" in ln else ln
        elif not desc:
            desc = ln
    # Metric text can wrap across lines in the cell; join any remainder.
    if metric:
        idx = [i for i, ln in enumerate(lines) if ln.upper().startswith("METRIC")]
        if idx and idx[0] + 1 < len(lines):
            metric = " ".join([metric] + lines[idx[0] + 1:])
    return label, desc, " ".join(metric.split())


def main():
    src = sys.argv[1] if len(sys.argv) > 1 else DEFAULT_XLSX
    wb = load_workbook(src, read_only=True, data_only=True)
    ws = wb[SHEET]
    rows = list(ws.iter_rows(values_only=True))

    pool_headers, pool_values = rows[1], rows[2]
    table_headers = rows[4]
    factors_row = rows[6]

    # --- funding pool block -------------------------------------------------
    # Year columns: the workbook labels three identical $11.6M tranches
    # (col9's "26-27" repeat is a source typo for 28-29 — the pool math
    # 9,040,307 + 35,000,000 - 1,200,000 - 8,040,307 = 34,800,000 = 3 x 11.6M
    # pins the window at three years, 2026-27 through 2028-29).
    pool = {
        "remaining_2025_26": _money(pool_values[2]),
        "one_time_2026_27": _money(pool_values[3]),
        "admin_cost": _money(pool_values[4]),
        "admin_cost_label": str(pool_headers[4]).strip(),
        "scaling_projects_tech": _money(pool_values[5]),
        "total_college_funding_label": str(pool_headers[6]).strip(),
        "available_per_year": _money(pool_values[7]),
        "years": ["2026-27", "2027-28", "2028-29"],
        "ccc_headcount": _num(pool_values[10]),
        "per_student": float(pool_values[11]),
        "projected": _money(pool_values[12]),
        "balance": round(float(pool_values[13]), 4),
    }
    pool["total_college_funding"] = _money(
        pool["remaining_2025_26"] + pool["one_time_2026_27"]
        - pool["admin_cost"] - pool["scaling_projects_tech"]
    )

    # --- priorities (header text + row-7 factor/rate constants) -------------
    priorities = []
    for key, col in zip(PRIORITY_KEYS, (4, 6, 8)):
        label, desc, metric = _parse_priority_header(table_headers[col])
        factor = float(factors_row[col])
        rate = float(factors_row[col + 1])
        priorities.append({
            "key": key,
            "label": label,
            "description": desc,
            "metric": metric,
            "factor": _num(factor),
            "rate": round(rate, 9),
            "share": round(factor * rate, 4),  # of the annual tranche
        })
    share_sum = sum(p["share"] for p in priorities)
    assert abs(share_sum - 1.0) < 1e-6, f"priority shares must sum to 1, got {share_sum}"

    # --- college rows (+ the ORDER-0 SYSTEM totals row) ----------------------
    def parse_row(r):
        return {
            "order": _num(r[0]),
            "college": str(r[1]).strip(),
            "headcount": _num(r[2]),
            "headcount_pct": _num(r[3]),
            "p1": _money(r[4]), "p1_heads": _num(r[5]),
            "p2": _money(r[6]), "p2_heads": _num(r[7]),
            "p3": _money(r[8]), "p3_heads": _num(r[9]),
            "total": _money(r[10]),
            "district": (str(r[11]).strip() if r[11] is not None else None),
            "county": (str(r[12]).strip() if r[12] is not None else None),
            # County context (U.S. Census 2022): estimated working adults with
            # some college, no degree; share of county population; college
            # headcount as pct of county total. "*Survey did not estimate"
            # rows surface as null.
            "working_adults": _num(r[13]) if not isinstance(r[13], str) else None,
            "county_pop_pct": _num(r[14]) if not isinstance(r[14], str) else None,
            "headcount_county_pct": _num(r[15]) if not isinstance(r[15], str) else None,
        }

    system = None
    colleges = []
    average_allocation = None
    footnotes = []
    for r in rows[7:]:
        loc = (str(r[1]).strip() if r[1] is not None else "")
        if r[8] == "AVERAGE ALLOCATION":
            average_allocation = _money(r[10])
            continue
        if not loc:
            continue
        if loc.startswith("*") or loc.lower().startswith("source:"):
            footnotes.append(loc)
            continue
        row = parse_row(r)
        if loc.upper() == "SYSTEM":
            system = row
        else:
            colleges.append(row)

    assert system is not None, "SYSTEM totals row not found"
    assert len(colleges) > 100, f"expected ~116 college rows, got {len(colleges)}"

    # --- verify the model math against every college row ---------------------
    worst = 0.0
    for c in colleges:
        for p in priorities:
            expect = c["headcount"] * p["rate"] * p["factor"] * pool["per_student"]
            got = c[p["key"]]
            worst = max(worst, abs(expect - got))
        worst = max(worst, abs((c["p1"] + c["p2"] + c["p3"]) - c["total"]))
    assert worst < 0.51, f"model math drifted from workbook values by {worst}"

    # --- reconcile the list against the workbook's own SYSTEM row ------------
    # Known 2026-06-11-edition variance: the college rows sum to 2,199,157
    # heads / $11,644,568, but the pool block's CCC HEADCOUNT (and therefore
    # the SYSTEM row + per-student rate) carries 2,190,740 / $11,600,000 —
    # short by exactly the LAST list row (Yuba, 8,417), i.e. the workbook's
    # SUM range appears to stop one row early. Surfaced, not corrected: the
    # artifact stays faithful to the source; the renderer footnotes it.
    list_heads = sum((c["headcount"] or 0) for c in colleges)
    list_total = round(sum(c["total"] for c in colleges), 2)
    if list_heads != system["headcount"] or abs(list_total - system["total"]) > 0.01:
        print(f"NOTE: source-model variance — college rows sum to {list_heads:,} heads / "
              f"${list_total:,.2f}/yr vs the workbook SYSTEM row {system['headcount']:,} / "
              f"${system['total']:,.2f} (flag for the next workbook edition).")

    data = {
        "model_version": "2026-06-11",
        "source": "funding/CPL_Funding_Model_2026.xlsx",
        "sheet": SHEET,
        "pool": pool,
        "priorities": priorities,
        "system": system,
        "colleges": colleges,
        "average_allocation": average_allocation,
        "footnotes": footnotes,
    }

    payload = json.dumps(data, indent=1, ensure_ascii=False)
    with open(OUT_JS, "w", encoding="utf-8") as f:
        f.write(
            "// CPL Implementation Funding model data — generated by\n"
            "// funding/_build_funding_data.py from " + data["source"] + "\n"
            "// (model version " + data["model_version"] + "). STATIC asset: committed, not\n"
            "// part of the daily cron. Do not hand-edit; re-run the builder instead.\n"
            "window.CPL_FUNDING = " + payload + ";\n"
        )
    print(f"wrote {os.path.normpath(OUT_JS)}: {len(colleges)} colleges + SYSTEM row, "
          f"{len(priorities)} priorities, max model-math drift {worst:.4f}")


if __name__ == "__main__":
    main()
