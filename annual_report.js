  // ─── docx export ───────────────────────────────────────────────────────────
  var docxLoading = false;
  function ensureDocx(cb) {
    if (window.docx) { cb(); return; }
    if (docxLoading) { var t = setInterval(function () { if (window.docx) { clearInterval(t); cb(); } }, 80); return; }
    docxLoading = true;
    var s = document.createElement("script");
    s.src = "docx.min.js";
    s.onload = function () { cb(); };
    s.onerror = function () { docxLoading = false; alert("Failed to load the Word library."); };
    document.head.appendChild(s);
  }
  function runs(D, text, base) {
    var parts = String(text).split(/(\*\*[^*]+\*\*)/g), out = [];
    parts.forEach(function (p) {
      if (!p) return;
      var bold = p.slice(0, 2) === "**" && p.slice(-2) === "**";
      out.push(new D.TextRun(Object.assign({ text: bold ? p.slice(2, -2) : p, bold: bold || base.bold }, base, { bold: bold || !!base.bold })));
    });
    return out.length ? out : [new D.TextRun(Object.assign({ text: text }, base))];
  }
  function buildDocx(md) {
    var D = window.docx;
    var kids = [];
    String(md).split("\n").forEach(function (raw) {
      var line = raw.trim();
      if (!line) { kids.push(new D.Paragraph({ children: [], spacing: { after: 80 } })); return; }
      if (/^#\s+/.test(line)) {
        kids.push(new D.Paragraph({ children: [new D.TextRun({ text: line.replace(/^#\s+/, ""), bold: true, size: 36, color: "0A2240", font: "Calibri" })], spacing: { after: 120 } }));
        return;
      }
      if (/^##\s+/.test(line)) {
        kids.push(new D.Paragraph({ children: [new D.TextRun({ text: line.replace(/^##\s+/, ""), bold: true, size: 28, color: "0A2240", font: "Calibri" })], spacing: { before: 280, after: 100 } }));
        return;
      }
      if (/^###\s+/.test(line)) {
        kids.push(new D.Paragraph({ children: [new D.TextRun({ text: line.replace(/^###\s+/, ""), bold: true, size: 23, color: "163A5F", font: "Calibri" })], spacing: { before: 180, after: 80 } }));
        return;
      }
      if (/^[-*]\s+/.test(line)) {
        kids.push(new D.Paragraph({ children: runs(D, line.replace(/^[-*]\s+/, ""), { size: 21, font: "Calibri", color: "333333" }), bullet: { level: 0 }, spacing: { after: 60 } }));
        return;
      }
      if (/^_.*_$/.test(line)) {
        kids.push(new D.Paragraph({ children: [new D.TextRun({ text: line.replace(/^_|_$/g, ""), italics: true, size: 19, color: "666666", font: "Calibri" })], spacing: { after: 120 } }));
        return;
      }
      kids.push(new D.Paragraph({ children: runs(D, line, { size: 21, font: "Calibri", color: "333333" }), spacing: { after: 120 } }));
    });
    return new D.Document({ sections: [{ properties: { page: { margin: { top: 1440, right: 1440, bottom: 1440, left: 1440 } } }, children: kids }] });
  }

