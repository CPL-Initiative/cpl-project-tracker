  // ─── Minimal markdown → HTML (headers, bold, bullets, paragraphs) ──────────
  function mdInline(s) {
    return esc(s).replace(/\*\*([^*]+)\*\*/g, "<strong>$1</strong>");
  }
  function mdToHtml(md) {
    var lines = String(md || "").split("\n");
    var html = [], inList = false;
    function closeList() { if (inList) { html.push("</ul>"); inList = false; } }
    lines.forEach(function (raw) {
      var line = raw.replace(/\s+$/, "");
      if (!line.trim()) { closeList(); return; }
      if (/^#\s+/.test(line)) { closeList(); html.push("<h1>" + mdInline(line.replace(/^#\s+/, "")) + "</h1>"); return; }
      if (/^##\s+/.test(line)) { closeList(); html.push("<h2>" + mdInline(line.replace(/^##\s+/, "")) + "</h2>"); return; }
      if (/^###\s+/.test(line)) { closeList(); html.push("<h3>" + mdInline(line.replace(/^###\s+/, "")) + "</h3>"); return; }
      if (/^[-*]\s+/.test(line)) {
        if (!inList) { html.push("<ul>"); inList = true; }
        html.push("<li>" + mdInline(line.replace(/^[-*]\s+/, "")) + "</li>");
        return;
      }
      closeList();
      // A whole line in _underscores_ is the italic note the Word export prints (the data date).
      if (/^_.*_$/.test(line)) { html.push("<p><em>" + mdInline(line.replace(/^_|_$/g, "")) + "</em></p>"); return; }
      html.push("<p>" + mdInline(line) + "</p>");
    });
    closeList();
    return html.join("\n");
  }

