  // KPIs: flatten nested {value} objects (mirrors generate_reports.js).
  function flattenKpis(rawKpis) {
    var kpis = {};
    Object.keys(rawKpis || {}).forEach(function (k) {
      var v = rawKpis[k];
      kpis[k] = (typeof v === 'object' && v !== null) ? (v.value || v) : v;
    });
    return kpis;
  }

  // Group projects by activity, preserving first-seen order (D.* helper rows
  // are excluded like every report generator does).
  function groupByActivity(projects) {
    var groups = {}, order = [];
    (projects || []).forEach(function (p) {
      if (!p || !p.id || String(p.id).indexOf('D.') === 0) return;
      var act = p.activity || 'Other';
      if (!groups[act]) { groups[act] = []; order.push(act); }
      groups[act].push(p);
    });
    order.sort();
    return { order: order, groups: groups };
  }

  // The report model: selected projects (live updates + RACI leads overlaid)
  // grouped by activity, with the activity-level live update attached. Pure —
  // everything the docx renderer needs, nothing DOM/docx-dependent.
  function buildReportModel(data, selectedPids, live) {
    data = data || {};
    live = live || { updates: {}, raci: {} };
    var pidSet = {};
    (selectedPids || []).forEach(function (pid) { pidSet[pid] = true; });
    var all = (data.projects || []).filter(function (p) {
      return p && p.id && String(p.id).indexOf('D.') !== 0;
    });
    var chosen = all.filter(function (p) { return pidSet[p.id]; }).map(function (p) {
      var q = {};
      for (var k in p) q[k] = p[k];
      var u = (live.updates || {})['project:' + p.id];
      if (updText(u)) { q.update = updText(u); q.update_date = updDate(u) || q.update_date; }
      var ln = leadNames((live.raci || {})['project:' + p.id]);
      if (ln.length) q.lead = ln.join(', ');
      return q;
    });
    var grouped = groupByActivity(chosen);
    var activities = grouped.order.map(function (actName) {
      var actNum = (String(actName).match(/Activity\s+(\d+)/) || [])[1];
      var u = actNum ? (live.updates || {})['activity:' + actNum] : null;
      return {
        name: actName,
        info: buildActivityDesc()['Activity ' + actNum] || {},
        update: updText(u) ? { body: updText(u), date: updDate(u) } : null,
        projects: grouped.groups[actName],
      };
    });
    return {
      kpis: flattenKpis(data.kpis),
      lastUpdated: data.last_updated || '',
      activities: activities,
      selectedCount: chosen.length,
      totalCount: all.length,
      partial: chosen.length < all.length,
    };
  }

  // ── Live overlay fetch (anon reads; soft-fails; CPL_DATA fallback) ──────────
  function fetchLiveOverlay() {
    function get(path) {
      return fetch(SUPABASE_URL + '/rest/v1/' + path, { headers: { apikey: SUPABASE_ANON } })
        .then(function (r) { return r.ok ? r.json() : []; })
        .catch(function () { return []; });
    }
    return Promise.all([
      get('item_updates?select=item_type,item_id,body,author,created_at&order=created_at.desc'),
      get('item_raci?select=item_type,item_id,raci'),
    ]).then(function (res) {
      var updates = latestByKey(res[0]);
      if (!Object.keys(updates).length && typeof window !== 'undefined'
          && window.CPL_DATA && window.CPL_DATA.live_updates) {
        updates = window.CPL_DATA.live_updates;
      }
      return { updates: updates, raci: raciByKey(res[1]) };
    });
  }

