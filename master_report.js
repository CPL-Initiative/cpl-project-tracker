  function open() {
    var m = document.getElementById('masterReportModal');
    if (!m) { buildModal(); m = document.getElementById('masterReportModal'); }
    if (m) m.style.display = 'block';
  }
  function close() {
    var m = document.getElementById('masterReportModal');
    if (m) m.style.display = 'none';
  }
  function setStatus(msg, color) {
    var el = document.getElementById('masterReportStatus');
    if (el) { el.textContent = msg; el.style.color = color || '#666'; }
  }
  function selectedPids() {
    var pids = [];
    Array.prototype.forEach.call(document.querySelectorAll('.mrpt-project-cb:checked'), function (cb) {
      pids.push(cb.getAttribute('data-pid'));
    });
    return pids;
  }

  // ── Generate flow ────────────────────────────────────────────────────────────
  function generate() {
    var pids = selectedPids();
    if (!pids.length) { setStatus('Please select at least one project.', '#c00'); return; }
    var btn = document.getElementById('masterReportGenBtn');
    btn.disabled = true;
    btn.textContent = 'Generating...';
    setStatus('Fetching the latest card updates...', '#4A90D9');

    fetchLiveOverlay().then(function (live) {
      var model = buildReportModel(window.CPL_DATA, pids, live);
      setStatus('Building Word document...', '#4A90D9');
      ensureDocxLib(function () {
        try {
          var doc = renderDocx(model);
          window.docx.Packer.toBlob(doc).then(function (blob) {
            var a = document.createElement('a');
            a.href = URL.createObjectURL(blob);
            a.download = 'CPL_Master_Report_' + new Date().toISOString().slice(0, 10) + '.docx';
            document.body.appendChild(a);
            a.click();
            document.body.removeChild(a);
            setStatus('Master report downloaded!', '#2A7D4F');
            btn.disabled = false;
            btn.textContent = 'Generate Master Report';
          }).catch(function (err) {
            setStatus('Error building document: ' + err.message, '#c00');
            btn.disabled = false;
            btn.textContent = 'Generate Master Report';
          });
        } catch (err) {
          setStatus('Error building document: ' + err.message, '#c00');
          btn.disabled = false;
          btn.textContent = 'Generate Master Report';
        }
      });
    });
  }

