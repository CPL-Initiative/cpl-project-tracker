#!/usr/bin/env python3
"""The CSR's stray codes, sorted by whether their answer can be checked (S435, 2026-10-20).

A stray is an identity code that is neither a Common SUBJ nor an umbrella code (`kb/_csr_trail.py`
mid_subject_codes). Two kinds:

1. **The identities carry a discipline.** The answer is the code, not the discipline: a re-key. Today these are
   all Foreign Languages (`kb/_fl_stray_remint.py`).
2. **The identities carry none.** Sam's ruling of 2026-09-08: a curator answers a blank; a session never fills
   one from a title. kb/_build_discipline_blanks_worklist.py reads the OTHER identities on the same prefix, which
   a stray by definition has none of. This reads a second, independent signal: the colleges' own. For each
   member course (college, local subject), what discipline do that college's other identities on the same
   local subject carry? The vote is per identity.

A code is **checkable** when that vote is at least `SHARE` of at least `VOTERS` voters. A checkable code still
waits on a person: the triage lists it with its titles so the reader can see whether the title agrees (the
second signal), and the card proposes the batch. Nothing here writes a discipline.

Read-only. `python3 kb/_csr_stray_triage.py` writes kb/csr_out/stray_triage.json and .md.
"""
import json
import os
from collections import Counter, defaultdict

HERE = os.path.dirname(os.path.abspath(__file__))
OUT = os.path.join(HERE, "csr_out")
SHARE, VOTERS = 0.85, 10


def load(name, key):
    with open(os.path.join(HERE, name), encoding="utf-8") as f:
        return json.load(f)[key]


def members(k, rec, memberships):
    if k in memberships:
        return [(m.get("college"), m.get("subject")) for m in memberships[k]]
    return [(rec.get("college"), rec.get("subject"))] if rec.get("college") else []


def triage(courses, singletons, memberships, strays):
    recs = {**courses, **singletons}
    index = defaultdict(Counter)
    for k, r in recs.items():
        if r.get("discipline") and k.split()[0] not in strays:
            for cs in set(members(k, r, memberships)):
                index[cs][r["discipline"]] += 1
    by_code = defaultdict(list)
    for k, r in sorted(recs.items()):
        code = k.split()[0]
        if code in strays and not r.get("discipline"):
            votes = Counter()
            for cs in set(members(k, r, memberships)):
                votes.update(index.get(cs, {}))
            by_code[code].append({"id": k, "title": r.get("common_title"), "top_code": r.get("top_code"),
                                  "colleges": sorted({c for c, _ in members(k, r, memberships) if c}),
                                  "votes": dict(votes.most_common(3))})
    rows = []
    for code, ids in by_code.items():
        agg = Counter()
        for i in ids:
            agg.update(i["votes"])
        n = sum(agg.values())
        lead, lead_n = (agg.most_common(1) or [(None, 0)])[0]
        share = round(lead_n / n, 2) if n else 0.0
        rows.append({"code": code, "identities": len(ids), "voters": n, "lead": lead, "share": share,
                     "runners_up": agg.most_common(3)[1:], "checkable": n >= VOTERS and share >= SHARE,
                     "colleges": sorted({c for i in ids for c in i["colleges"]}),
                     "titles": [i["title"] for i in ids], "ids": [i["id"] for i in ids]})
    rows.sort(key=lambda x: (not x["checkable"], -x["identities"], x["code"]))
    return rows


def main():
    with open(os.path.join(OUT, "latest.json"), encoding="utf-8") as f:
        mc = json.load(f)["_mid_codes"]
    strays = {s["code"] for s in mc["strays"]}
    with_disc = [s for s in mc["strays"] if "(no discipline)" not in s["disciplines"]]
    rows = triage(load("coci_minted_courses.json", "courses"), load("coci_minted_singletons.json", "courses"),
                  dict(load("coci_minted_memberships.json", "memberships")), strays)
    ck = [r for r in rows if r["checkable"]]
    doc = {"_generated_by": "kb/_csr_stray_triage.py", "_scanned_at": mc.get("_scanned_at"),
           "_gate": {"share": SHARE, "voters": VOTERS},
           "_counts": {"stray_codes": len(strays), "with_discipline": len(with_disc),
                       "no_discipline": len(rows), "checkable": len(ck),
                       "checkable_identities": sum(r["identities"] for r in ck)},
           "with_discipline": with_disc, "no_discipline": rows}
    with open(os.path.join(OUT, "stray_triage.json"), "w", encoding="utf-8") as f:
        json.dump(doc, f, indent=1, ensure_ascii=False)
        f.write("\n")
    c = doc["_counts"]
    L = ["# The CSR's stray codes, by whether the answer can be checked", "",
         f"Generated by `kb/_csr_stray_triage.py` from `kb/csr_out/latest.json`. {c['stray_codes']} stray codes: "
         f"{c['with_discipline']} on identities that carry a discipline (a re-key, `kb/_fl_stray_remint.py`), "
         f"{c['no_discipline']} on identities that carry none. Of those, {c['checkable']} codes "
         f"({c['checkable_identities']} identities) pass the gate: the colleges' other identities on the same "
         f"local subject agree on one discipline, at least {int(SHARE * 100)}% of at least {VOTERS} votes.", "",
         "A checkable code still waits on a person (Sam's ruling of 2026-09-08). Read the titles beside the vote.", "",
         "| Code | Identities | Votes | Lead discipline | Share | Checkable | Colleges | Sample titles |",
         "|---|---|---|---|---|---|---|---|"]
    for r in rows:
        L.append(f"| {r['code']} | {r['identities']} | {r['voters']} | {r['lead'] or ''} | {r['share']} | "
                 f"{'yes' if r['checkable'] else 'no'} | {len(r['colleges'])} | "
                 f"{'; '.join(t or '' for t in r['titles'][:3])} |")
    with open(os.path.join(OUT, "stray_triage.md"), "w", encoding="utf-8") as f:
        f.write("\n".join(L) + "\n")
    print(json.dumps(c))


if __name__ == "__main__":
    main()
