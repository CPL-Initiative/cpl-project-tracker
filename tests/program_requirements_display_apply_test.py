#!/usr/bin/env python3
"""The display apply writes exactly what the reviewed receipt prints, to the
rows it names, and files how to take it back.

WHY. kb/_program_requirements_display_apply.py moves the display write from a
session's apply_migration to the college workflow's display job (S356): a
college's receipt is megabytes. The ways that goes wrong are known in advance:

  * The receipt's display JSON is a SQL literal: a quote inside it is doubled
    (Cerritos College''s CourseLeaf reading procedure). A parser that stops at
    the first quote writes a truncated display, or none.
  * A line of another shape (a hand edit, a delta's guard) must stop the apply,
    never be skipped: what applies is what was reviewed.
  * The page and the table must hold one build. A page that mixes builds, or a
    receipt whose statements carry another build, is refused.
  * A delta receipt writes only the rows that moved; it never stands for a build.
  * The rollback is the before-build of every row written: null goes back to
    null, an older build goes back by its own receipt.

Each is pinned against the module's own functions, with no network.
Run from repo root: python3 tests/program_requirements_display_apply_test.py
"""
import json
import os
import shutil
import sys
import tempfile

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
sys.path.insert(0, os.path.join(ROOT, "kb"))
import _program_requirements_display_apply as A  # noqa: E402

passed = 0


def check(cond, why):
    global passed
    if not cond:
        print("FAIL: " + why)
        sys.exit(1)
    passed += 1


def stmt(college, cn, display):
    lit = json.dumps(display, ensure_ascii=False).replace("'", "''")
    return ("insert into public.program_requirement_records (college, control_number, program_title, measure, "
            "record, checks, display) select r.college, r.control_number, r.program_title, r.measure, r.record, "
            "r.checks, '%s'::jsonb from public.program_requirement_records r where r.college = '%s' and "
            "r.control_number = '%s' on conflict (college, control_number) do update set display = "
            "excluded.display;" % (lit, college.replace("'", "''"), cn.replace("'", "''")))


BUILD = "5be53871ebf4"
d1 = {"build": BUILD, "notes": [{"where": "Cerritos College's CourseLeaf reading procedure",
                                 "text": "a quote ' and a doubled '' and ::jsonb from inside"}]}
d2 = {"build": BUILD, "counts": {"courses": 4}}
text = "\n".join(["-- Generated by kb/_build_roep_display.py (build %s)." % BUILD,
                  stmt("Cerritos College", "02201", d1), stmt("Mt. San Antonio College", "03086", d2), ""])

rows = A.parse(text)
check(len(rows) == 2, "every statement parses, the comment line skipped")
check(rows[0]["display"] == d1, "a quote inside the display literal survives, and so does text that looks "
      "like the statement's own tail")
check(rows[0]["college"] == "Cerritos College" and rows[0]["control_number"] == "02201"
      and rows[1]["college"] == "Mt. San Antonio College", "each display goes to the key its statement names")
check(A.parse(stmt("O'Neill College", "1", d2))[0]["college"] == "O'Neill College",
      "a quote in the college's name is unescaped")

for bad, why in ((text + "update public.program_requirement_records set display = null;\n", "a stray UPDATE"),
                 (stmt("Cerritos College", "02201", d2).replace(" on conflict", " and true on conflict"),
                  "a statement with an extra guard"),
                 (stmt("Cerritos College", "02201", d2)[:-40], "a truncated statement")):
    try:
        A.parse(bad)
        check(False, "%s must stop the parse" % why)
    except ValueError:
        check(True, "%s stops the parse" % why)

check(A.page_build('{"build": "%s"}, {"build": "%s"}' % (BUILD, BUILD)) == BUILD, "one build on the page names it")
try:
    A.page_build('{"build": "%s"}, {"build": "2360b83e8100"}' % BUILD)
    check(False, "a page mixing builds is refused")
except SystemExit:
    check(True, "a page mixing builds is refused")

tmp = tempfile.mkdtemp()
try:
    full = os.path.join(tmp, "program_requirement_records_display_2026-10-06_%s.sql" % BUILD)
    open(full, "w").write(text)
    open(os.path.join(tmp, "program_requirement_records_display_2026-10-08_%s_s347_delta.sql" % BUILD), "w").write("")
    open(os.path.join(tmp, "program_requirement_records_display_2026-10-08_%s_delta.sql" % BUILD), "w").write("")
    check(A.receipt_for(BUILD, tmp) == full, "the full receipt stands for the build, never a delta")

    held = {"Cerritos College|02201": None, "Mt. San Antonio College|03086": "2360b83e8100"}
    calls = []

    def fake(method, path_qs, body=None):
        calls.append((method, path_qs, body))
        key = ("Cerritos College|02201" if "Cerritos" in path_qs else "Mt. San Antonio College|03086")
        if method == "GET":
            return [{"build": held[key]}]
        return [{"control_number": key.split("|")[1]}]

    rec = A.apply(rows, BUILD, full, "123", request=fake)
    patches = [c for c in calls if c[0] == "PATCH"]
    check(rec["written"] == 2 and not rec["errors"] and not rec["missing"], "both rows written")
    check(all(set(b) == {"display"} for _, _, b in patches) and patches[0][2]["display"] == d1,
          "a PATCH writes display alone, exactly as the receipt prints it")
    check([c[0] for c in calls] == ["GET", "PATCH", "GET", "PATCH"], "each row's build is read before it is written")
    check("college=eq.Cerritos%20College&control_number=eq.02201" in patches[0][1]
          and "college=eq.Mt.%20San%20Antonio%20College" in patches[1][1], "each write is filtered to its key")
    check(rec["rollback"]["to_null"] == ["Cerritos College|02201"]
          and rec["rollback"]["reapply"] == {"2360b83e8100": ["Mt. San Antonio College|03086"]},
          "the rollback names what goes back to null and what goes back by its own receipt")
    check(A.applied_path(full, "123").endswith("_%s.applied_123.json" % BUILD), "the applied record sits beside the receipt")

    def gone(method, path_qs, body=None):
        return [] if method == "GET" and "03086" in path_qs else fake(method, path_qs, body)

    calls.clear()
    rec = A.apply(rows, BUILD, full, "124", request=gone)
    check(rec["missing"] == ["Mt. San Antonio College|03086"] and rec["written"] == 1,
          "a key the table does not hold is named, never inserted")
finally:
    shutil.rmtree(tmp)

print("ok: program requirements display apply pass (%d checks)" % passed)
