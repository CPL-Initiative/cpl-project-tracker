#!/usr/bin/env python3
"""No display receipt in a commit, and no apply without a stored, checked receipt (S680, #3476).

WHY. Sam, 2026-11-17: "Let's move the bloated data out first thing and make sure we
don't allow to go beyond a limit." The display receipts were 1,531 MB of a 2.0 GB
clone. From S680 git ignores them, the display job builds each on the runner, stores
it in the private cpl-receipts bucket and names it with its sha256 in
kb/receipts/index.json, and the apply reads it back from there. The ways that goes
wrong, each pinned here with no network:

  (a) the apply reads a copy whose bytes are not the ones stored: it must read the
      bucket first, fall back to the repo copy, and refuse both unless their sha256 is
      the index's, before any table read;
  (b) a malformed index entry, or two entries for one build, or one name filed again
      with other bytes;
  (c) the ignore rule missing a display receipt, or catching the small applied records
      beside it (they are the rollback, and stay committed);
  (d) the workflow applying before it stores: the display job must build, then store,
      then apply, with nothing between that lets the apply run after a failed store,
      and its commit step must refuse a staged display receipt;
  and the store itself: an upload that fails or reads back with other bytes files no
  index entry and exits non-zero; the runner's rebuild is refused when its build is not
  the page's.

Run from the repo root: python3 tests/display_receipt_store_test.py
"""
