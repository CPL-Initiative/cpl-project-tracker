def receipt_bytes(build=BUILD):
    text = "\n".join(["-- Generated by kb/_build_roep_display.py (build %s, built 2026-11-13)." % build,
                      stmt("Cerritos College", "02201", {"build": build, "n": 1}),
                      stmt("Mt. San Antonio College", "03086", {"build": build, "n": 2}), ""])
    buf = io.BytesIO()
    with gzip.GzipFile(filename="", mode="wb", fileobj=buf, mtime=0) as gz:
        gz.write(text.encode("utf-8"))
    return buf.getvalue()


class Bucket:
    """A fake cpl-receipts: put/get by object name; `corrupt` returns other bytes on get,
    `fail_put`/`fail_get` raise as the Storage API would."""

    def __init__(self):
        self.objects, self.puts, self.gets = {}, [], []
        self.corrupt = self.fail_put = self.fail_get = False

    def put(self, obj, data):
        self.puts.append(obj)
        if self.fail_put:
            raise urllib.error.URLError("connection refused")
        if obj in self.objects:
            return "exists"
        self.objects[obj] = data
        return "stored"

    def get(self, obj):
        self.gets.append(obj)
        if self.fail_get or obj not in self.objects:
            raise urllib.error.HTTPError("u", 404, "Object not found", {}, None)
        return self.objects[obj] + (b"x" if self.corrupt else b"")


