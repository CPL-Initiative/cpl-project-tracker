/*
 * COBI — Card RACI overlay  (window.CPL_CARD_RACI)
 *
 * Two read-only behaviors on the Activities & Projects cards, both sourced LIVE
 * from the Supabase `item_raci` table (the single source of truth managed on the
 * Team & RACI tab) so the cards stop showing the stale, pre-RACI `projects.lead`:
 *
 *   1. LEAD ← RACI. Each card carries a generator-stamped
 *        <span class="cpl-raci-lead" data-raci-key="project:1.1">Old Lead</span>
 *      The overlay replaces its text with the item's RACI **Responsible** member(s)
 *      (falling back to Accountable, then leaving the creation-era lead when the
 *      item has no RACI row yet). So sub-activity 1.1 reads "Malone Dunlavy" (its
 *      RACI R) instead of "Terence Nelson" (the abandoned projects.lead).
 *
 *   2. HOVER ROSTER. Hovering (or focusing) a 👥 RACI button — `.raci-link` /
 *      `.act-raci-link`, both stamped with `data-raci-key` — pops a compact
 *      R/A/C/I roster so you can see who's involved without leaving the card.
 *
 * STATIC asset — NOT regenerated by excel_to_dashboard.py; read-only (no writes,
 * no auth). Mirrors the anon-read pattern of card_updates.js.
 */
(function () {
  "use strict";

  var SUPABASE_URL = "https://hvuwhnbuahrtptokpqfh.supabase.co";
  var SUPABASE_ANON = "eyJhbGciOiJIUzI1NiIsInR5cCI6IkpXVCJ9.eyJpc3MiOiJzdXBhYmFzZSIsInJlZiI6Imh2dXdobmJ1YWhydHB0b2twcWZoIiwicm9sZSI6ImFub24iLCJpYXQiOjE3NzU1NzI0ODEsImV4cCI6MjA5MTE0ODQ4MX0.p0q-93iTM0GkF2z8_q7Vvl1tsX9SFGMM-W7Wdx7WfmM";

  var ROLE_LABELS = { R: "Responsible", A: "Accountable", C: "Consulted", I: "Informed" };

  // ── Pure helpers (also exported for tests) ──────────────────────────────────
  function escapeHtml(s) {
    return (s == null ? "" : String(s)).replace(/[&<>"']/g, function (c) {
      return { "&": "&amp;", "<": "&lt;", ">": "&gt;", '"': "&quot;", "'": "&#39;" }[c];
    });
  }

  // Names out of one role array ([{name,email}] — tolerant of bare strings).
  function roleNames(arr) {
    return (arr || [])
      .map(function (m) { return m && m.name ? m.name : (typeof m === "string" ? m : ""); })
      .filter(Boolean);
  }

  // The card "Lead" for an item = its Responsible member(s); fall back to
  // Accountable so an A-only item still names an owner. Empty array → the caller
  // keeps the creation-era lead text (the item isn't in RACI yet).
  function leadNames(raci) {
    if (!raci) return [];
    var r = roleNames(raci.R);
    if (r.length) return r;
    return roleNames(raci.A);
  }

  // Index item_raci rows → { "project:1.1": {R:[],A:[],C:[],I:[]}, ... }.
  function byKey(rows) {
    var out = {};
    (rows || []).forEach(function (r) {
      if (!r || r.item_type == null || r.item_id == null) return;
      out[r.item_type + ":" + r.item_id] = r.raci || {};
    });
    return out;
  }

  // Compact R/A/C/I roster markup for the hover popover. Each populated role is a
  // row "<RoleLabel> name, name". Empty roles are skipped; an item with nothing
  // assigned yields a gentle placeholder. All names escaped (reviewer-written).
  function rosterHtml(raci) {
    var rows = ["R", "A", "C", "I"].map(function (k) {
      var ns = roleNames(raci && raci[k]);
      if (!ns.length) return "";
      return (
        '<div style="margin:0.15rem 0;line-height:1.35;">' +
          '<span style="display:inline-block;min-width:1.1rem;font-weight:700;color:var(--gold-accent,#c9a227);">' + k + "</span>" +
          '<span style="color:#888;font-size:0.66rem;margin-right:0.3rem;">' + ROLE_LABELS[k] + "</span>" +
          '<span>' + ns.map(escapeHtml).join(", ") + "</span>" +
        "</div>"
      );
    }).filter(Boolean).join("");
    return rows || '<div style="color:#888;font-style:italic;">No one assigned yet — open Team &amp; RACI to set.</div>';
  }

  // ── DOM application ─────────────────────────────────────────────────────────
  var _raci = null;

  function applyLeads(root) {
    if (!_raci) return;
    var scope = root || document;
    var hooks = scope.querySelectorAll(".cpl-raci-lead[data-raci-key]");
    Array.prototype.forEach.call(hooks, function (hook) {
      var key = hook.getAttribute("data-raci-key");
      var ns = leadNames(_raci[key]);
      // An optional wrapper that should appear ONLY when RACI names a lead — used
      // by Activity headers + sub-activity cards, which have no creation-era lead
      // of their own. Project cards have no wrapper (their Lead row is always shown).
      var row = hook.closest ? hook.closest(".cpl-raci-lead-row") : null;
      // Remember the creation-era text once so a later DELETE-all can restore it.
      if (hook.getAttribute("data-orig") == null) hook.setAttribute("data-orig", hook.textContent || "");
      var orig = hook.getAttribute("data-orig") || "";
      var hasOrig = !!orig && orig !== "—"; // — = the "—" placeholder
      if (ns.length) {
        var txt = ns.join(", ");
        var sig = "raci:" + txt;
        if (row) row.style.display = "";
        if (hook.getAttribute("data-shown") === sig) return;
        hook.textContent = txt;
        hook.setAttribute("data-shown", sig);
        hook.setAttribute("data-from-raci", "1");
        hook.setAttribute("title", "Responsible (from the Team & RACI matrix)");
      } else if (hook.getAttribute("data-from-raci") === "1") {
        // Had a RACI lead, now cleared → restore the creation-era lead (project
        // cards) or hide the placeholder-only row (activity / sub-activity).
        hook.textContent = orig || "—";
        hook.removeAttribute("data-from-raci");
        hook.removeAttribute("data-shown");
        hook.setAttribute("title", "No Responsible set in the Team & RACI matrix yet");
        if (row && !hasOrig) row.style.display = "none";
      }
    });
  }

  // ── Hover roster popover (delegated; works for cards added after boot) ───────
  var _pop = null, _popKey = null;
  function ensurePop() {
    if (_pop) return _pop;
    _pop = document.createElement("div");
    _pop.className = "cpl-raci-pop";
    _pop.setAttribute("role", "tooltip");
    _pop.style.cssText =
      "position:fixed;z-index:10000;max-width:280px;max-height:240px;overflow:auto;" +
      "background:#fff;border:1px solid #d8d8d8;border-radius:8px;padding:0.5rem 0.6rem;" +
      "box-shadow:0 6px 24px rgba(0,0,0,0.18);font-size:0.72rem;color:#333;display:none;" +
      "pointer-events:none;";
    document.body.appendChild(_pop);
    return _pop;
  }
  function showPop(target) {
    if (!_raci) return;
    var key = target.getAttribute("data-raci-key");
    if (!key) return;
    var pop = ensurePop();
    if (_popKey !== key) {
      pop.innerHTML =
        '<div style="font-weight:700;color:var(--navy-primary,#1b3a5c);margin-bottom:0.25rem;">Team &amp; RACI</div>' +
        rosterHtml(_raci[key] || {});
      _popKey = key;
    }
    var r = target.getBoundingClientRect();
    pop.style.display = "block";
    // Default below the trigger; flip above if it would overflow the viewport.
    var top = r.bottom + 6;
    if (top + pop.offsetHeight > window.innerHeight - 8) top = Math.max(8, r.top - pop.offsetHeight - 6);
    var left = Math.min(r.left, window.innerWidth - pop.offsetWidth - 8);
    pop.style.top = top + "px";
    pop.style.left = Math.max(8, left) + "px";
  }
  function hidePop() { if (_pop) { _pop.style.display = "none"; _popKey = null; } }

  function bindHover() {
    if (bindHover._done || typeof document === "undefined") return;
    bindHover._done = true;
    function trig(e) {
      var t = e.target && e.target.closest && e.target.closest(".raci-link[data-raci-key], .act-raci-link[data-raci-key]");
      return t || null;
    }
    document.addEventListener("mouseover", function (e) { var t = trig(e); if (t) showPop(t); });
    document.addEventListener("mouseout", function (e) {
      var t = trig(e);
      if (t && !(e.relatedTarget && t.contains(e.relatedTarget))) hidePop();
    });
    document.addEventListener("focusin", function (e) { var t = trig(e); if (t) showPop(t); });
    document.addEventListener("focusout", function (e) { var t = trig(e); if (t) hidePop(); });
    // A scroll/resize would leave the fixed popover stranded — just dismiss it.
    window.addEventListener("scroll", hidePop, true);
    window.addEventListener("resize", hidePop);
  }

  function fetchRaci() {
    return fetch(SUPABASE_URL + "/rest/v1/item_raci?select=item_type,item_id,raci", {
      headers: { apikey: SUPABASE_ANON }
    })
      .then(function (r) { return r.ok ? r.json() : []; })
      .catch(function () { return []; });
  }

  // _loading is a TRUE in-flight guard, cleared when the fetch settles (mirrors
  // card_updates.js — a permanently-set guard would freeze every later run()).
  var _loading = false, _again = false;
  function run() {
    bindHover();
    if (_loading) { _again = true; applyLeads(); return; }
    _loading = true; _again = false;
    fetchRaci().then(function (rows) {
      _raci = byKey(rows);
      applyLeads();
      hidePop(); // force the next hover to rebuild from fresh data
    }).then(null, function () {}).then(function () {
      _loading = false;
      if (_again) run();
    });
  }

  // ── Boot ────────────────────────────────────────────────────────────────────
  if (typeof document !== "undefined" && document.addEventListener) {
    if (document.readyState === "loading") {
      document.addEventListener("DOMContentLoaded", run);
    } else {
      run();
    }
    if (typeof window !== "undefined" && window.addEventListener) {
      // Re-apply when the card tabs activate (the fetch may resolve before the
      // pane is in view), and when RACI is saved on the Team & RACI tab.
      window.addEventListener("cpl-tab-activated", function (e) {
        var tab = e && e.detail && e.detail.tab;
        if (tab === "activities-projects" || tab === "dashboard" || tab == null) run();
      });
      window.addEventListener("cpl-raci-updated", function () { run(); });
    }
  }

  var api = {
    run: run,
    applyLeads: applyLeads,
    byKey: byKey,
    leadNames: leadNames,
    roleNames: roleNames,
    rosterHtml: rosterHtml,
    escapeHtml: escapeHtml,
    _setRaci: function (m) { _raci = m; } // test hook
  };
  if (typeof window !== "undefined") window.CPL_CARD_RACI = api;
  else if (typeof module !== "undefined" && module.exports) module.exports = api;
})();
