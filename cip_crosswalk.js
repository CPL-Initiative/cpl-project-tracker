  function buildFinder() {
    var finder = el("div", { class: "cipx-finder" }, [
      el("div", { class: "cipx-fnd-h" }, ["Not sure which code? Describe your program"]),
      el("div", { class: "cipx-fnd-sub" }, ["Type what you're building in plain English and we'll surface the closest CIP codes to review."]),
    ]);
    var fin = el("input", { class: "cipx-fnd-in", type: "text", "aria-label": "Describe your program",
      placeholder: "e.g. medical assisting · GIS mapping · wildland firefighting · HVAC technician" });
    var _ft;
    fin.oninput = function () { var v = fin.value; clearTimeout(_ft); _ft = setTimeout(function () { renderFinder(v); }, 180); };
    fin.onkeydown = function (ev) { if (ev.key === "Enter") { ev.preventDefault(); renderFinder(fin.value); } };
    finder.appendChild(fin);
    finderOut = el("div", { class: "cipx-fnd-out" }, []);
    finder.appendChild(finderOut);
    return finder;
  }

  function buildBar() {
    var bar = el("div", { class: "cipx-bar" }, []);

    // search
    var input = el("input", { class: "cipx-search", id: "cipx-q", type: "search", autocomplete: "off",
      "aria-label": "Search CIP codes",
      placeholder: "Search by code, program title, or keyword — e.g. nursing, welding, 51.3801" });
    inputRef = input;
    var _t;
    input.oninput = function () { var v = input.value; clearTimeout(_t); _t = setTimeout(function () { st.q = v.toLowerCase().trim(); st.limit = PAGE; render(); }, 140); };
    bar.appendChild(el("div", { class: "cipx-searchrow" }, [input]));

    var controls = el("div", { class: "cipx-controls" }, []);

    // category pills
    var pills = el("div", { class: "cipx-pills" }, []); pillsRef = pills;
    [["all", "All"], ["CTE", "CTE"], ["Non-CTE", "Non-CTE"], ["Both", "Both"], ["Noncredit", "Noncredit"]].forEach(function (p) {
      var b = el("button", { class: "cipx-pill", type: "button", "aria-pressed": st.cat === p[0] ? "true" : "false" }, [p[1]]);
      b.onclick = function () {
        st.cat = p[0]; st.limit = PAGE;
        Array.prototype.forEach.call(pills.querySelectorAll(".cipx-pill"), function (x) { x.setAttribute("aria-pressed", "false"); });
        b.setAttribute("aria-pressed", "true");
        render();
      };
      pills.appendChild(b);
    });
    controls.appendChild(pills);

    // C-ID/CCN toggle chip (ANDs with the category)
    controls.appendChild(el("span", { class: "cipx-chipsep" }, []));
    var xferChip = el("button", { class: "cipx-pill cipx-pill-xfer", type: "button", "aria-pressed": st.xfer ? "true" : "false",
      title: "CIP codes whose courses carry a C-ID (transfer-model articulation) or CCN (common course number). A course-level floor — not a guarantee of full transferability." },
      ["🎓 C-ID/CCN"]);
    xferRef = xferChip;
    xferChip.onclick = function () { st.xfer = !st.xfer; xferChip.setAttribute("aria-pressed", st.xfer ? "true" : "false"); st.limit = PAGE; render(); };
    controls.appendChild(xferChip);

    // CIP family select
    var fam = el("select", { class: "cipx-fsel", "aria-label": "CIP family" }, [el("option", { value: "" }, ["All CIP families"])]);
    famRef = fam;
    Object.keys(FAMS).sort().forEach(function (f) { fam.appendChild(el("option", { value: f }, [f + " · " + FAMS[f]])); });
    fam.onchange = function () { st.fam = fam.value; st.limit = PAGE; render(); };
    controls.appendChild(fam);

    // include retired/reserved
    var tog = el("label", { class: "cipx-retiredtog", title: "Retired = moved/deleted in 2020. Reserved = placeholder codes." }, []);
    var cb = el("input", { type: "checkbox" }); cbRef = cb;
    cb.onchange = function () { st.showRetired = cb.checked; st.limit = PAGE; render(); };
    tog.appendChild(cb); tog.appendChild(document.createTextNode("Include retired / reserved"));
    controls.appendChild(tog);

    bar.appendChild(controls);
    countHost = el("div", { class: "cipx-count" }, []);
    bar.appendChild(countHost);
    return bar;
  }

  function footer() {
    var active = ROWS.filter(function (r) { return GOFORWARD[r.cat]; }).length;
    return el("div", { class: "cipx-foot" }, [
      "CIP-2020 data from the Chancellor's Office CIP Searchable Workbook (2026-07-15 cut). " +
      active.toLocaleString() + " active CIP codes shown by default; retired and reserved codes are " +
      "hidden unless you tick the box above. The CTE / non-CTE / both / noncredit label reflects the " +
      "Chancellor's Office certified CIP CTE designations.",
    ]);
  }

  function rebuildShell() {
    var root = document.getElementById(ROOT_ID);
    if (!root) return;
    clear(root);
    root.removeAttribute("style");
    var wrap = el("div", { class: "cipx" }, []);
    wrap.appendChild(header());
    wrap.appendChild(buildFinder());
    wrap.appendChild(buildBar());
    listHost = el("div", { class: "cipx-list" }, []);
    wrap.appendChild(listHost);
    wrap.appendChild(footer());
    root.appendChild(wrap);
    render();
  }

