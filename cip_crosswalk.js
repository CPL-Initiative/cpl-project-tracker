  // highlight query tokens in a string → array of nodes (text-only; XSS-safe)
  function hl(s) {
    s = s || "";
    if (!st.q) return [s];
    var toks = st.q.split(/\s+/).filter(Boolean).map(function (t) { return t.replace(/[.*+?^${}()|[\]\\]/g, "\\$&"); });
    if (!toks.length) return [s];
    var re = new RegExp("(" + toks.join("|") + ")", "ig");
    var out = [], last = 0, m;
    while ((m = re.exec(s))) {
      if (m.index > last) out.push(s.slice(last, m.index));
      out.push(el("mark", {}, [m[0]]));
      last = m.index + m[0].length;
      if (re.lastIndex === m.index) re.lastIndex++;
    }
    if (last < s.length) out.push(s.slice(last));
    return out;
  }

  // ── plain-English finder (Phase 0: NO backend — grounded client-side retrieval
  //    over the real CIP records, so it can never invent a code) ──
  var STOP = { i: 1, a: 1, an: 1, the: 1, to: 1, for: 1, of: 1, in: 1, on: 1, at: 1, and: 1, or: 1, my: 1, our: 1, we: 1, want: 1,
    wanting: 1, need: 1, would: 1, like: 1, which: 1, what: 1, should: 1, cip: 1, code: 1, codes: 1, assign: 1, use: 1,
    using: 1, program: 1, programs: 1, course: 1, courses: 1, degree: 1, certificate: 1, "new": 1, build: 1, building: 1,
    start: 1, starting: 1, launch: 1, launching: 1, offer: 1, offering: 1, is: 1, are: 1, me: 1, help: 1, find: 1, about: 1,
    "with": 1, that: 1, "this": 1, it: 1, "do": 1, how: 1, best: 1, fit: 1 };
  function esc(s) { return s.replace(/[.*+?^${}()|[\]\\]/g, "\\$&"); }
  function stem(w) { return w.length < 5 ? w : (w.replace(/(ings?|edly|ed|ations?|tions?|ers?|ors?|ies|es|s)$/, "") || w); }
  function tokenize(q) { return (q || "").toLowerCase().split(/[^a-z0-9]+/).filter(function (w) { return w && w.length > 1 && !STOP[w]; }); }
  function rankCIP(q) {
    var toks = tokenize(q);
    if (!toks.length) return [];
    // word-boundary + stem = prefix-on-word-boundary: "weld"→welding/welder,
    // "assist"→assistant/assisting, but "gis" WON'T match "logistics"/"registered".
    var res = toks.map(function (w) { return { tok: w, s: stem(w), re: new RegExp("\\b" + esc(stem(w))) }; });
    var out = [];
    for (var i = 0; i < ROWS.length; i++) {
      var r = ROWS[i];
      if (!GOFORWARD[r.cat]) continue;               // active codes only
      var t = (r.t || "").toLowerCase(), d = (r.def || "").toLowerCase(), e = (r.ex || "").toLowerCase();
      var score = 0, hits = 0, matched = [];
      for (var j = 0; j < res.length; j++) {
        var m = res[j], hit = 0;
        if (m.re.test(t)) { score += (t.indexOf(m.s) === 0 ? 9 : 7); hit = 1; }  // title word
        if (m.re.test(e)) { score += 3; hit = 1; }                              // examples
        if (m.re.test(d)) { score += 1; hit = 1; }                              // definition
        if (hit) { hits++; matched.push(m.tok); }
      }
      if (hits) {
        score += hits * hits * 2;                     // reward covering more of the query
        if (t === (q || "").toLowerCase().trim()) score += 60; // exact title
        out.push({ r: r, score: score, matched: matched });
      }
    }
    out.sort(function (a, b) { return b.score - a.score || (a.r.t < b.r.t ? -1 : 1); });
    return out.slice(0, 6);
  }
  function renderFinder(q) {
    clear(finderOut);
    if (!tokenize(q).length) return;
    var hits = rankCIP(q);
    if (!hits.length) {
      finderOut.appendChild(el("div", { class: "cipx-fnd-empty" },
        ["No close matches yet — try a program name or a key skill (e.g. \"welding\", \"medical assisting\", \"GIS\")."]));
      return;
    }
    finderOut.appendChild(el("div", { class: "cipx-fnd-lead" },
      ["Closest CIP codes for “" + q.trim() + "” — open each to confirm against its definition:"]));
    hits.forEach(function (h) {
      var r = h.r;
      var caret = el("span", { class: "cipx-caret" }, ["▸"]);
      var crow = el("div", { class: "cipx-fnd-crow", role: "button", tabindex: "0" }, [
        caret, el("span", { class: "cipx-code" }, [r.code]),
        el("span", { class: "cipx-fnd-ct" }, [r.t]),
        r.cat ? el("span", { class: catClass(r.cat), title: catTip(r.cat) }, [r.cat]) : null,
      ]);
      var card = el("div", { class: "cipx-fnd-card" }, [crow]);
      if (h.matched.length) card.appendChild(el("div", { class: "cipx-fnd-why" }, ["matched: " + h.matched.join(", ")]));
      var open = false, det = null;
      function tog() {
        open = !open; caret.textContent = open ? "▾" : "▸";
        if (open) { det = detail(r); card.appendChild(det); } else if (det) { card.removeChild(det); det = null; }
      }
      crow.onclick = tog;
      crow.onkeydown = function (ev) { if (ev.key === "Enter" || ev.key === " ") { ev.preventDefault(); tog(); } };
      finderOut.appendChild(card);
    });
    finderOut.appendChild(el("div", { class: "cipx-fnd-foot" },
      ["Suggestions to review — the CIP definition is the final word, and your college enters the chosen code in COCI. (An AI-assisted version is on the way.)"]));
  }

  // ── list + detail ─────────────────────────────────────────────────────────────
  function render() {
    var rows = filtered();
    clear(countHost);
    countHost.appendChild(el("span", { class: "cipx-cnum" }, [
      rows.length.toLocaleString() + " CIP code" + (rows.length === 1 ? "" : "s") +
      (rows.length > st.limit ? "  ·  showing " + st.limit.toLocaleString() : ""),
    ]));
    var af = activeFilterLabels();
    if (af.length) countHost.appendChild(el("span", { class: "cipx-cfilters" }, [" · " + af.join(" · ")]));
    if (af.length || st.q) {
      var clr = el("button", { class: "cipx-clearbtn", type: "button" },
        ["✕ Clear " + (af.length && st.q ? "search + filters" : (st.q ? "search" : "filters"))]);
      clr.onclick = resetAll;
      countHost.appendChild(clr);
    }
    var csv = el("button", { class: "cipx-csv", type: "button", title: "Download the current filtered list as CSV",
      onclick: function () { exportCsv(rows); } }, ["⬇ CSV"]);
    countHost.appendChild(csv);

    clear(listHost);
    if (!rows.length) {
      listHost.appendChild(el("div", { class: "cipx-empty" }, ["No CIP codes match — try a different word or clear the filters."]));
      return;
    }
    var shown = rows.slice(0, st.limit);
    shown.forEach(function (r) {
      var isOpen = !!st.open[r.code];
      var badges = el("div", { class: "cipx-tags" }, []);
      if (r.act === "New") badges.appendChild(el("span", { class: "cipx-new", title: "New in the 2020 CIP edition" }, ["NEW"]));
      if (r.cat) badges.appendChild(el("span", { class: catClass(r.cat), title: catTip(r.cat) }, [r.cat]));
      var row = el("div", { class: "cipx-row", role: "button", tabindex: "0" }, [
        el("span", { class: "cipx-caret" }, [isOpen ? "▾" : "▸"]),
        el("span", { class: "cipx-code" }, [r.code]),
        el("span", { class: "cipx-ttl" }, hl(r.t)),
        badges,
      ]);
      var item = el("div", { class: "cipx-item" + (isOpen ? " cipx-open" : "") }, [row]);
      row.onclick = function () { toggle(r.code); };
      row.onkeydown = function (e) { if (e.key === "Enter" || e.key === " ") { e.preventDefault(); toggle(r.code); } };
      if (isOpen) item.appendChild(detail(r));
      listHost.appendChild(item);
    });
    if (rows.length > st.limit) {
      listHost.appendChild(el("div", { class: "cipx-more" }, [
        el("button", { class: "cipx-morebtn", type: "button", onclick: function () { st.limit += PAGE; render(); } },
          ["Show " + Math.min(PAGE, rows.length - st.limit).toLocaleString() + " more"]),
      ]));
    }
  }

  function detail(r) {
    var box = el("div", { class: "cipx-detail" }, []);
    box.appendChild(el("p", { class: "cipx-def" }, [r.def || "No published definition for this code."]));
    if (r.ex) box.appendChild(el("p", { class: "cipx-ex" }, [el("b", {}, ["Examples: "]), r.ex]));
    var meta = el("div", { class: "cipx-dmeta" }, []);
    if (r.fam) meta.appendChild(el("span", {}, [el("b", {}, ["CIP family " + r.fam + " · "]), FAMS[r.fam] || ""]));
    if (r.x) meta.appendChild(el("span", { class: "cipx-xnote",
      title: "At least one TOP that maps to this CIP has courses carrying a C-ID (transfer-model articulation) or CCN (AB 1111 common course number). A course-level floor — not full CSU/UC transferability." },
      ["🎓 C-ID/CCN coursework exists"]));
    box.appendChild(meta);
    box.appendChild(el("a", { class: "cipx-ncesbtn", target: "_blank", rel: "noopener", href: NCES },
      ["Look up " + r.code + " in the NCES CIP-2020 list ↗"]));
    return box;
  }
  function toggle(code) { if (st.open[code]) delete st.open[code]; else st.open[code] = true; render(); }

  // ── CSV export of the current filtered list ───────────────────────────────────
  function exportCsv(rows) {
    var out = ["CIP Code,Title,Category,Family,Family Title,2020 CIP Action,C-ID/CCN,Definition"];
    rows.forEach(function (r) {
      function q(v) { return '"' + String(v == null ? "" : v).replace(/"/g, '""') + '"'; }
      out.push([q(r.code), q(r.t), q(r.cat), q(r.fam), q(FAMS[r.fam] || ""),
                q(r.act), q(r.x ? "Yes" : "No"), q(r.def)].join(","));
    });
    var blob = new Blob([out.join("\n")], { type: "text/csv" });
    var a = document.createElement("a");
    a.href = URL.createObjectURL(blob);
    a.download = "cip_code_taxonomy.csv";
    document.body.appendChild(a); a.click(); document.body.removeChild(a);
  }

