/* cip_crosswalk.js — "CIP Code Taxonomy" reference tab (window.CPL_CIP_CROSSWALK)
 *
 * The CO is transitioning course/program coding from TOP to CIP effective fall
 * 2026 (ESS 26-06). This tab is the faculty-facing REFERENCE MANUAL — the
 * successor to the CCC TOP Code Manual, an "easy button" that replaces the
 * multi-tab spreadsheet ESS was going to email to the field. It surfaces the
 * full federal CIP-2020 list: search, a plain-English program finder, and each
 * code's certified CTE category, definition, examples, family, and a course-
 * level C-ID/CCN floor. COE hosts the actual TOP↔CIP crosswalk (linked out) —
 * per the CO's reframe (Jenni Abbott, AA), TOP→CIP is one-to-many and we are
 * the reference, not a crosswalk recreator. No "suggest" form (CO direction).
 *
 * Ported from the locked prototype at docs/cip_prototype/ (prototype→lock→port).
 * STATIC — NOT regenerated by excel_to_dashboard.py. Lazy-loaded on first
 * #cip-crosswalk open (boot block in both HTMLs). Data: window.CIP_CROSSWALK
 * (cip_crosswalk_data.js, built by kb/_build_cip_crosswalk.py) — {fams, rows}.
 * Injects its own scoped CSS (everything under .cipx, no :root) so the daily
 * regen can't strand it and there's no Rule-4 mirror beyond the boot <script>.
 * DOM built with createElement/textContent (never innerHTML with data) for
 * CodeQL XSS safety. Tests: tests/cip_crosswalk.test.js
 */
