  // overlay rows -> { pid: {state, reason, updated_by, updated_at} }, dropping
  // malformed rows (no project_id, or a state outside the allowed pair).
  function indexOverlay(rows) {
    var out = {};
    (rows || []).forEach(function (r) {
      if (!r || r.project_id == null) return;
      if (r.state !== "tabled" && r.state !== "archived") return;
      out[String(r.project_id)] = {
        state: r.state,
        reason: r.reason || "",
        updated_by: r.updated_by || "",
        updated_at: r.updated_at || ""
      };
    });
    return out;
  }

  function fmtDate(iso) {
    if (!iso) return "";
    var d = new Date(iso);
    if (isNaN(d.getTime())) return String(iso).slice(0, 10);
    try { return d.toLocaleDateString(undefined, { year: "numeric", month: "short", day: "numeric" }); }
    catch (e) { return d.toISOString().slice(0, 10); }
  }

