  function doRestore(pid, btn) {
    var sess = getSession();
    if (!sess) { return; }
    var entry = entryFor(pid);
    var name = entry ? entryNameOf(entry) : pid;
    var prevMeta = _overlay[pid];
    if (btn) { btn.disabled = true; btn.textContent = "Restoring…"; }
    // Optimistic: un-hide the grid card (if present) + remove the entry.
    showCard(pid);
    removeEntry(pid);
    mountControls();
    deleteLifecycle(pid, sess).then(function (r) {
      if (r.ok) { delete _overlay[pid]; }
      else {
        // rollback
        if (prevMeta) { hideCard(pid, prevMeta.state); addEntry(pid, name, prevMeta); mountControls(); }
        alert("Restore failed (HTTP " + r.status + "). " +
          (r.status === 401 || r.status === 403 ? "Your sign-in/phrase may have expired." : ""));
      }
    }).catch(function (e) {
      if (prevMeta) { hideCard(pid, prevMeta.state); addEntry(pid, name, prevMeta); mountControls(); }
      alert("Restore failed: " + (e && e.message || "network error"));
    });
  }

  // ── Delegated clicks (controls are injected dynamically) ─────────────────────
  function onClick(e) {
    var t = e.target;
    while (t && t !== document) {
      if (t.classList && t.classList.contains("plc-table-btn")) { e.preventDefault(); openTableModal(t.getAttribute("data-pid")); return; }
      if (t.classList && t.classList.contains("tabled-restore")) { e.preventDefault(); doRestore(t.getAttribute("data-pid"), t); return; }
      if (t.classList && t.classList.contains("plc-modal-overlay")) { closeModal(); return; }
      t = t.parentNode;
    }
  }

