  function matches(r, f) {
    if (f.path !== "all" && (r.pathway || []).indexOf(f.path) === -1) return false;
    if (f.status !== "all" && r.status !== f.status) return false;
    if (f.cite !== "all" && (r.citations || []).indexOf(f.cite) === -1) return false;
    if (f.q) {
      var hay = [r.title, r.summary, r.consideration, r.instrument, r.grp]
        .concat(r.citations || []).join(" ").toLowerCase();
      if (hay.indexOf(f.q) === -1) return false;
    }
    return true;
  }

