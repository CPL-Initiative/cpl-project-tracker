    var html = '<html xmlns:o="urn:schemas-microsoft-com:office:office" xmlns:w="urn:schemas-microsoft-com:office:word" xmlns="http://www.w3.org/TR/REC-html40"><head><meta charset="utf-8"><title>CPL Reform Priorities</title></head><body style="font-family:Calibri,Arial,sans-serif;color:#23252b;margin:0.6in">' + docBody(doc) + "</body></html>";
