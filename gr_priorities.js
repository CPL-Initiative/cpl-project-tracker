  // Append rich inline HTML to `node`, building only allowlisted elements.
  function appendRich(node, html) {
    html = String(html == null ? "" : html).replace(/^<p>/, "").replace(/<\/p>$/, "");
    RICH.lastIndex = 0;
    var last = 0, m;
    function txt(s) { if (s) node.appendChild(document.createTextNode(decode(s))); }
    while ((m = RICH.exec(html))) {
      txt(html.slice(last, m.index));
      if (m[1] !== undefined) {
        var url = m[1];
        if (/^https:\/\//.test(url)) {         // guard: only real https links
          var a = el("a", { href: url, target: "_blank", rel: "noopener" });
          a.textContent = decode(m[2]);
          node.appendChild(a);
        } else { txt(m[2]); }
      } else if (m[3] !== undefined) {
        node.appendChild(el("b", { text: decode(m[3]) }));
      } else if (m[4] !== undefined) {
        node.appendChild(el("i", { text: decode(m[4]) }));
      }
      last = RICH.lastIndex;
    }
    txt(html.slice(last));
    return node;
  }
