/*
 * COBI — Card action opener  (window.CPL_CARD_ACTIONS)
 *
 * The Activity / Project cards (Activities & Projects tab + Dashboard activity
 * metrics) carry 📝 Update and 📣 Nudge affordances emitted by the generator as
 *   <a href="#raci" class="update-link" onclick="…setItem('cpl_update_focus','project:5.1')…">
 * Historically those navigated to the Team & RACI tab, where raci.js read the
 * stashed key and opened the composer / nudge. Sam (2026-06-29): "none of this
 * should direct the user to RACI, rather to the Activity and Project tab."
 *
 * This tiny, globally-loaded module makes the popup open RIGHT THERE instead:
 *   • it intercepts clicks on the card .update-link / .nudge-link affordances,
 *     cancels the #raci navigation, lazy-loads raci.js, and opens the popup in
 *     place via window.CPL_RACI_TAB.openCardUpdate / openCardNudge;
 *   • it consumes the nudge-email deep-link (?update=<key> / ?nudge=<key>) on ANY
 *     tab at boot, so an emailed link opens the composer wherever it lands (the
 *     email now points at #activities-projects).
 * The composer carries its own team-phrase unlock box, so the user can edit
 * without leaving the tab.
 *
 * It also lands a link to one card (S438, Sam 2026-10-20: "Add links to go
 * directly to the Activity cards"): #activities-projects/card-<id> and
 * #activities-projects/activity-<N>, which the Annual Workplan Goals tab prints
 * under each sub-activity and on each Activity header. tabs.js opens the tab (the
 * slug names no section, so it scrolls to the top); focusCardFromHash then opens
 * the folded section, clears a filter that hides the card, scrolls to it and marks
 * it for a moment, with focus on it for a keyboard or screen reader.
 *
 * STATIC asset — NOT regenerated by excel_to_dashboard.py; no writes, no auth of
 * its own (raci.js owns the Supabase write + the phrase gate). Loaded after
 * tabs.js (it uses CPL_TABS.loadScript). Mirrored in BOTH HTMLs (Rule 4).
 */
(function () {
  "use strict";

  // The card affordances whose clicks we open in place (and the kind each maps to).
  var UPDATE_SEL = "a.update-link";
  var NUDGE_SEL = "a.nudge-link, a.act-nudge-link";

  // The item key (`activity:N` | `project:<id>`) lives in the link's inline
  // onclick — read it from there (deterministic, independent of event order)
  // with the sessionStorage the onclick sets as a fallback.
  function keyFromLink(a, kind) {
    var oc = (a && a.getAttribute && a.getAttribute("onclick")) || "";
    var m = oc.match(/cpl_(?:update|nudge)_focus'\s*,\s*'([^']+)'/);
    if (m && m[1]) return m[1];
    try { return sessionStorage.getItem(kind === "nudge" ? "cpl_nudge_focus" : "cpl_update_focus"); } catch (e) { return null; }
  }

  // Lazy-load raci.js (idempotent via CPL_TABS.loadScript) then open the popup.
  function openInPlace(kind, key) {
    if (!key || key.indexOf(":") < 0) return false;
    var tabs = (typeof window !== "undefined") && window.CPL_TABS;
    if (!tabs || typeof tabs.loadScript !== "function") return false;
    tabs.loadScript("raci.js", "CPL_RACI_TAB", function () {
      var api = window.CPL_RACI_TAB;
      if (!api) return;
      if (kind === "nudge") { if (api.openCardNudge) api.openCardNudge(key); }
      else if (api.openCardUpdate) api.openCardUpdate(key);
    });
    return true;
  }

  function onClick(e) {
    var t = e && e.target;
    if (!t || !t.closest) return;
    var a = t.closest(UPDATE_SEL + ", " + NUDGE_SEL);
    if (!a) return;
    var cls = a.className || "";
    var kind = /nudge-link/.test(cls) ? "nudge" : "update";
    var key = keyFromLink(a, kind);
    if (!key) return; // unknown key — let the default #raci navigation happen
    if (openInPlace(kind, key)) {
      e.preventDefault();
      // The inline onclick just stashed the key in sessionStorage; clear it so a
      // later manual visit to #raci doesn't replay this as a stale focus-open.
      try { sessionStorage.removeItem(kind === "nudge" ? "cpl_nudge_focus" : "cpl_update_focus"); } catch (x) {}
    }
  }

  // The nudge email links to …?update=<key>#activities-projects (or ?nudge=).
  // Consume it on ANY tab at boot, open the popup in place, and strip the param
  // (so a reload / raci.js's own consumer don't re-fire it).
  function consumeQueryParam() {
    var key = null, kind = "update";
    try {
      var qp = new URLSearchParams(location.search || "");
      if (qp.get("update")) { key = qp.get("update"); kind = "update"; qp.delete("update"); }
      else if (qp.get("nudge")) { key = qp.get("nudge"); kind = "nudge"; qp.delete("nudge"); }
      if (key) {
        var qs = qp.toString();
        history.replaceState(null, "", location.pathname + (qs ? "?" + qs : "") + location.hash);
      }
    } catch (e) {}
    if (key) openInPlace(kind, key);
  }

  // ── A link to one card ──────────────────────────────────────────────────────
  // #activities-projects/card-1.1 → { kind: "card", id: "1.1" };
  // #activities-projects/activity-3 → { kind: "activity", id: "3" }.
  function cardTargetFromHash(hash) {
    var m = /^#activities-projects\/(card|activity)-(.+)$/.exec(hash || "");
    if (!m) return null;
    var id = m[2];
    try { id = decodeURIComponent(id); } catch (e) {}
    return { kind: m[1], id: id };
  }
  function findCardTarget(t) {
    var pane = document.getElementById("tab-activities-projects") || document;
    var q = (window.CSS && CSS.escape) ? CSS.escape(t.id) : String(t.id).replace(/"/g, '\\"');
    if (t.kind === "card") return pane.querySelector('.activity-kpi-card[data-pid="' + q + '"]');
    var group = pane.querySelector('.activity-group[data-activity-id="' + q + '"]');
    if (group) return group;
    // A page built before the group carried data-activity-id: its RACI link names it.
    var raci = pane.querySelector('.act-raci-link[data-raci-key="activity:' + q + '"]');
    return raci && raci.closest ? raci.closest(".activity-group") : null;
  }
  // Hidden by a filter (an inline display:none on the card or its group) or a
  // hidden attribute, between the node and the tab pane.
  function isHidden(node) {
    var pane = document.getElementById("tab-activities-projects");
    for (var n = node; n && n !== pane && n.nodeType === 1; n = n.parentNode) {
      if (n.hidden || (n.style && n.style.display === "none")) return true;
    }
    return false;
  }
  function ensureTargetCss() {
    if (document.getElementById("cpl-card-target-css")) return;
    var st = document.createElement("style");
    st.id = "cpl-card-target-css";
    st.textContent = ".activity-kpi-card.cpl-card-target, .activity-group.cpl-card-target "
      + "{ outline:3px solid var(--focus-ring);outline-offset:3px;border-radius:8px; }"
      + ".activity-kpi-card[tabindex]:focus:not(.cpl-card-target), .activity-group[tabindex]:focus:not(.cpl-card-target) { outline:0; }";
    document.head.appendChild(st);
  }
  function focusCardFromHash() {
    var t = cardTargetFromHash(location.hash);
    if (!t) return null;
    var node = findCardTarget(t);
    if (!node) return null;
    var wrap = document.getElementById("workplanProjectsWrapper");
    if (wrap && wrap.classList.contains("collapsed") && wrap.contains(node)) wrap.classList.remove("collapsed");
    if (isHidden(node) && typeof window.resetFilters === "function") window.resetFilters();
    // Still hidden (tabled, say): land on its Activity instead.
    if (isHidden(node) && t.kind === "card" && node.closest) node = node.closest(".activity-group") || node;
    ensureTargetCss();
    var reduce = !!(window.matchMedia && window.matchMedia("(prefers-reduced-motion: reduce)").matches);
    var raf = window.requestAnimationFrame || function (f) { return setTimeout(f, 0); };
    raf(function () {
      node.classList.add("cpl-card-target");
      if (!node.hasAttribute("tabindex")) node.setAttribute("tabindex", "-1");
      // Land clear of the tab's sticky actions bar: at the top it covered the card's
      // id and name (measured 145px at 1440). Its height is read now, since it wraps.
      var bar = document.querySelector("#tab-activities-projects .filter-bar");
      var clear = 0;
      try { if (bar && /sticky|fixed/.test(getComputedStyle(bar).position)) clear = bar.getBoundingClientRect().height; } catch (e) {}
      node.style.scrollMarginTop = Math.round(clear + 12) + "px";
      // The top, not the center: a card with a long update history runs past the
      // screen (3.1.2 measured 1,554px), and centered it hid its own name.
      if (node.scrollIntoView) node.scrollIntoView({ behavior: reduce ? "auto" : "smooth", block: "start" });
      try { node.focus({ preventScroll: true }); } catch (e) {}
      setTimeout(function () { node.classList.remove("cpl-card-target"); }, 2500);
    });
    return node;
  }

  // ── Boot ────────────────────────────────────────────────────────────────────
  if (typeof document !== "undefined" && document.addEventListener) {
    document.addEventListener("click", onClick, false);
    if (document.readyState === "loading") {
      document.addEventListener("DOMContentLoaded", consumeQueryParam);
    } else {
      consumeQueryParam();
    }
    // tabs.js announces every activation, the first one at load included.
    window.addEventListener("cpl-tab-activated", function (e) {
      if (e && e.detail && e.detail.tab === "activities-projects") focusCardFromHash();
    });
  }

  var api = { keyFromLink: keyFromLink, openInPlace: openInPlace, onClick: onClick, consumeQueryParam: consumeQueryParam,
    cardTargetFromHash: cardTargetFromHash, focusCardFromHash: focusCardFromHash };
  if (typeof window !== "undefined") window.CPL_CARD_ACTIONS = api;
  else if (typeof module !== "undefined" && module.exports) module.exports = api;
})();
