  function byCollege(rows) {
    var map = {}, order = [];
    rows.forEach(function (d) {
      var k = d.college_name || ("college " + d.college_id);
      if (!map[k]) { map[k] = []; order.push(k); }
      map[k].push(d);
    });
    order.sort(function (a, b) {
      var sa = map[a].reduce(function (t, r) { return t + (r.rows || 0); }, 0);
      var sb = map[b].reduce(function (t, r) { return t + (r.rows || 0); }, 0);
      return sb - sa || a.localeCompare(b);
    });
    return { map: map, order: order };
  }

