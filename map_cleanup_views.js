/*
 * CSM clean-up views (COBI) — map_cleanup_views.js
 *
 * Two READ-ONLY views for the ITPI Customer Success team, rendered above the
 * curated defect register on the MAP Data Quality tab.
 *
 *   1. Clean-up worklist   public.map_cleanup_worklist     (college x class)
 *   2. Cx exhibit guidance public.map_cx_exhibit_guidance  (per ACE exhibit)
 *
 * SAM'S FRAMING, 2026-08-20, and it is the whole design:
 *   "my goal is to guide CSM team to make changes in MAP rather than house and
 *    maintain data layers in COBI"
 *
 * So this file deliberately has NO write path, NO status field, NO check-off and
 * NO notes. Both tables carry SELECT-only RLS policies (verified: polcmd 'r',
 * no INSERT/UPDATE/DELETE policy exists on either), and both are rebuilt nightly
 * inside map_promote_custom_reports(). COBI is where you find out what to change;
 * MAP is where you change it. A progress field here would immediately become a
 * second system of record that disagrees with MAP by the next morning.
 *
 * Every row therefore ends in something you can DO in MAP, and each college has
 * a copy action that produces text you can take to them. That mirrors the
 * register's own "Copy for MAP devs" affordance beside it.
 *
 * ⚠️ AN RLS-FILTERED READ RETURNS 200 + []. Locked and genuinely-empty are the
 * same HTTP response, so this module never renders "no work" without a session —
 * it renders the unlock prompt. See renderState().
 *
 * STATIC asset (not regenerated by excel_to_dashboard.py). Team-phrase gated via
 * window.CPL_TEAM_PHRASE, which is shared with the register, so unlocking either
 * one unlocks both. All CSS injected from here, scoped under `.cpl-mcw` (one
 * file, no Rule-4 HTML mirror needed for the styles).
 */
